"""Executable system tools and OS integrations for JARVIS.

This module defines the actual functions that JARVIS can invoke on the host
machine in response to user voice commands. Each tool is decorated with `@tool`
to register it with the function calling system in `registry.py`.
"""

from datetime import datetime
import subprocess
import webbrowser
from registry import tool


# Conversational Tools

@tool(
    name="normal_response",
    description="Użyj tego narzędzia ZAWSZE, gdy użytkownik nie wydaje polecenia systemowego, tylko prowadzi zwykłą rozmowę (np. wita się, pyta co u ciebie, żartuje, pyta, co myślisz o czymś).",
    parameters={
        "type": "object",
        "properties": {
            "text_for_user": {
                "type": "string",
                "description": "Content of your response in Polish."
            }
        },
        "required": ["text_for_user"]
    }
)
def normal_response(text_for_user: str) -> str:
    """Return conversational response text for ordinary chat interactions.

    Invoked when the user is chatting, greeting, joking, or asking general questions
    that do not require executing system actions or OS-level commands.

    Args:
        text_for_user (str): Spoken response content generated by the LLM in Polish.

    Returns:
        str: Dialogue text to be vocalized back to the user via TTS.
    """
    return text_for_user


# Time & Date Tools

@tool(
    name="get_time",
    description="Zwraca aktualną godzinę. Użyj TYLKO gdy użytkownik pyta o godzinę, np. 'która godzina?', 'jaki mamy czas?'."
)
def get_time() -> str:
    """Retrieve the current system time formatted as a natural Polish sentence.

    Returns:
        str: Current time response string (e.g. 'Jest godzina 14:35.').
    """
    now = datetime.now()
    return f"Jest godzina {now.hour}:{now.minute:02d}."


@tool(
    name="get_date",
    description="Zwraca aktualną datę. Użyj gdy użytkownik pyta o dzisiejszą datę, dzień tygodnia, lub jaki mamy dzień."
)
def get_date() -> str:
    """Retrieve the current system date formatted as a natural Polish sentence.

    Returns:
        str: Current date response string with day of week and full date.
    """
    days_pl = {
        0: "poniedziałek", 1: "wtorek", 2: "środa", 3: "czwartek",
        4: "piątek", 5: "sobota", 6: "niedziela"
    }
    months_pl = {
        1: "stycznia", 2: "lutego", 3: "marca", 4: "kwietnia",
        5: "maja", 6: "czerwca", 7: "lipca", 8: "sierpnia",
        9: "września", 10: "października", 11: "listopada", 12: "grudnia"
    }
    now = datetime.now()
    day_name = days_pl[now.weekday()]
    month_name = months_pl[now.month]
    return f"Dziś jest {day_name}, {now.day} {month_name} {now.year} roku."


# Application Launchers

@tool(
    name="open_app",
    description="Otwiera aplikację na komputerze po nazwie. Użyj gdy użytkownik prosi o otwarcie, włączenie lub uruchomienie dowolnej aplikacji (np. notatnik, kalkulator, przeglądarka, paint, terminal, steam (wymawiane 'stim')).",
    parameters={
        "type": "object",
        "properties": {
            "app_name": {
                "type": "string",
                "description": "Nazwa pliku wykonywalnego aplikacji, np. 'notepad.exe', 'calc.exe', 'mspaint.exe', 'cmd.exe', 'explorer.exe', 'msedge.exe'."
            }
        },
        "required": ["app_name"]
    }
)
def open_app(app_name: str) -> str:
    """Launch an application by executable name as a background subprocess.

    Rejects executable names containing path separators ('/' or '\\') to prevent
    arbitrary directory traversal and only launches programs discoverable via PATH
    or standard Windows application registrations.

    Args:
        app_name (str): Name of the executable to launch (e.g. 'notepad.exe', 'calc.exe').

    Returns:
        str: Spoken confirmation or error message in Polish.
    """
    if '\\' in app_name or '/' in app_name:
        return "Przepraszam, nie mogę uruchomić aplikacji z podaną ścieżką."

    try:
        subprocess.Popen([app_name])
        friendly_name = app_name.replace('.exe', '').replace('.', ' ').capitalize()
        return f"{friendly_name} został otwarty."
    except FileNotFoundError:
        return f"Nie znalazłem aplikacji o nazwie {app_name}."
    except OSError as e:
        return f"Nie udało się otworzyć aplikacji: {e}"


@tool(
    name="close_app",
    description="Zamyka uruchomioną aplikację po nazwie procesu. Użyj gdy użytkownik prosi o zamknięcie, wyłączenie lub zabicie aplikacji.",
    parameters={
        "type": "object",
        "properties": {
            "process_name": {
                "type": "string",
                "description": "Nazwa procesu do zamknięcia, np. 'notepad.exe', 'calc.exe', 'mspaint.exe'."
            }
        },
        "required": ["process_name"]
    }
)
def close_app(process_name: str) -> str:
    """Terminate a running application by process name using Windows taskkill.

    Runs `taskkill /im <process_name> /f` to terminate all matching process instances.

    Args:
        process_name (str): Name of the process image to terminate (e.g. 'notepad.exe').

    Returns:
        str: Spoken confirmation or error message in Polish.
    """
    try:
        result = subprocess.run(
            ["taskkill", "/im", process_name, "/f"],
            capture_output=True, text=True, encoding="utf-8"
        )
        if result.returncode == 0:
            friendly_name = process_name.replace('.exe', '').capitalize()
            return f"{friendly_name} został zamknięty."
        else:
            return f"Nie udało się zamknąć {process_name}. Może nie jest uruchomiony?"
    except Exception as e:
        return f"Błąd przy zamykaniu aplikacji: {e}"


# Web & Search Tools

@tool(
    name="search_web",
    description="Wyszukuje frazę w Google za pomocą domyślnej przeglądarki. Użyj gdy użytkownik prosi o wyszukanie, znalezienie lub sprawdzenie czegoś w internecie.",
    parameters={
        "type": "object",
        "properties": {
            "query": {
                "type": "string",
                "description": "Fraza do wyszukania w Google."
            }
        },
        "required": ["query"]
    }
)
def search_web(query: str) -> str:
    """Open a Google search query in the system's default web browser.

    Args:
        query (str): Search term or phrase to look up.

    Returns:
        str: Spoken confirmation message in Polish.
    """
    url = f"https://www.google.com/search?q={query}"
    webbrowser.open(url)
    return f"Wyszukuję: {query}"


@tool(
    name="open_website",
    description="Otwiera stronę internetową w domyślnej przeglądarce. Użyj gdy użytkownik prosi o otwarcie konkretnej strony (np. YouTube, Gmail, Facebook).",
    parameters={
        "type": "object",
        "properties": {
            "url": {
                "type": "string",
                "description": "Adres URL strony do otwarcia, np. 'https://youtube.com'."
            }
        },
        "required": ["url"]
    }
)
def open_website(url: str) -> str:
    """Open a website URL in the default web browser.

    Automatically prepends 'https://' if the URL does not begin with an HTTP/HTTPS scheme.

    Args:
        url (str): Destination web address to open (e.g. 'youtube.com' or 'https://google.com').

    Returns:
        str: Spoken confirmation message in Polish.
    """
    if not url.startswith(('http://', 'https://')):
        url = 'https://' + url
    webbrowser.open(url)
    return f"Otwieram stronę."


# System Information Tools

@tool(
    name="system_command",
    description="Wykonuje bezpieczne polecenie systemowe i zwraca jego wynik. Użyj gdy użytkownik pyta o informacje systemowe, np. 'ile mam RAM-u?', 'jaki mam procesor?', 'jaki jest mój IP?'. Dozwolone komendy: systeminfo, ipconfig, hostname, whoami, tasklist.",
    parameters={
        "type": "object",
        "properties": {
            "command": {
                "type": "string",
                "description": "Polecenie systemowe do wykonania. TYLKO: systeminfo, ipconfig, hostname, whoami, tasklist."
            }
        },
        "required": ["command"]
    }
)
def system_command(command: str) -> str:
    """Execute a whitelisted system diagnostic command and return its output.

    Enforces a strict whitelist of safe, read-only Windows utility commands
    ('systeminfo', 'ipconfig', 'hostname', 'whoami', 'tasklist') to prevent
    unintended modifications or execution of arbitrary commands. Truncates
    output to 500 characters to keep responses manageable.

    Args:
        command (str): System command string to execute.

    Returns:
        str: Captured command stdout or error message in Polish.
    """
    allowed_commands = {"systeminfo", "ipconfig", "hostname", "whoami", "tasklist"}
    base_command = command.strip().split()[0].lower()

    if base_command not in allowed_commands:
        return f"Przepraszam, komenda '{command}' nie jest dozwolona ze względów bezpieczeństwa."

    try:
        result = subprocess.run(
            command, capture_output=True, text=True,
            encoding="utf-8", shell=True, timeout=15
        )
        output = result.stdout.strip()
        if len(output) > 500:
            output = output[:500] + "... (skrócono)"
        return output if output else "Komenda nie zwróciła żadnych danych."
    except subprocess.TimeoutExpired:
        return "Komenda przekroczyła limit czasu."
    except Exception as e:
        return f"Błąd przy wykonywaniu komendy: {e}"
