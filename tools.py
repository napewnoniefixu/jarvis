"""Executable system tools and OS integrations for JARVIS.

This module defines the actual functions that JARVIS can invoke on the host
machine in response to user voice commands. Each tool is decorated with `@tool`
to register it with the function calling system in `registry.py`.
"""

from datetime import datetime
import subprocess
from registry import tool

@tool(
    name="zwykla_odpowiedz",
    description="Użyj tego narzędzia ZAWSZE, gdy użytkownik nie wydaje polecenia systemowego, tylko prowadzi zwykłą rozmowę (np. wita się, pyta co u ciebie, żartuje).",
    parameters={
        "type": "object",
        "properties": {
            "tekst_dla_uzytkownika": {
                "type": "string",
                "description": "Treść twojej odpowiedzi w języku polskim."
            }
        },
        "required": ["tekst_dla_uzytkownika"]
    }
)
def zwykla_odpowiedz(tekst_dla_uzytkownika: str) -> str:
    """Return conversational response text for ordinary chat interactions.

    Invoked when the user is chatting, greeting, joking, or asking general questions
    that do not require executing system actions or OS-level commands.

    Args:
        tekst_dla_uzytkownika (str): Spoken response content generated by the LLM in Polish.

    Returns:
        str: Dialogue text to be vocalized back to the user via TTS.
    """
    return tekst_dla_uzytkownika

@tool(
    name="open_notepad", 
    description="Otwiera systemowy edytor tekstu (notatnik). Użyj TYLKO gdy użytkownik jawnie prosi o otwarcie, włączenie lub uruchomienie notatnika.")
def open_notepad() -> str:
    """Launch the Windows Notepad application as a background subprocess.

    Returns:
        str: Spoken confirmation message indicating the action was performed.
    """
    subprocess.Popen(["notepad.exe"])
    return "Notatnik został otwarty."


@tool(
    name="get_time", 
    description="Zwraca aktualną godzinę. UŻYJ TYLKO I WYŁĄCZNIE, gdy użytkownik zada wprost pytanie: 'która godzina?' lub 'jaki mamy czas?'. ABSOLUTNIE NIE UŻYWAJ tego narzędzia do odpowiedzi na powitania, zwroty typu 'co u ciebie' lub w luźnej rozmowie. W takich sytuacjach zignoruj narzędzie i odpowiedz po prostu tekstem.")
def get_time() -> str:
    """Retrieve the current system time formatted as a natural Polish sentence.

    Returns:
        str: Current time response string (e.g. 'Jest godzina 14:35.').
    """
    now = datetime.now()
    return f"Jest godzina {now.hour}:{now.minute:02d}."